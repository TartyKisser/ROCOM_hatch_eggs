import json
import sys
from itertools import groupby
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


def unicode_ranges(codepoints):
    for _, points in groupby(enumerate(sorted(codepoints)), key=lambda pair: pair[1] - pair[0]):
        span = [point for _, point in points]
        first, last = span[0], span[-1]
        yield f"U+{first:X}" if first == last else f"U+{first:X}-{last:X}"


def save_woff2(font, path):
    font.flavor = "woff2"
    font.save(path)
    print(f"{path.name} {path.stat().st_size / 1024:.1f} KiB")


def save_subset(font, path, text, *, include_ascii=True):
    needed = {ord(character) for character in text}
    if include_ascii:
        needed.update(range(0x20, 0x7F))
    codepoints = {point for point in needed & font.getBestCmap().keys() if point >= 0x20}
    options = subset.Options()
    options.name_IDs = ["*"]
    options.name_legacy = True
    options.name_languages = ["*"]
    font_subset = subset.Subsetter(options=options)
    font_subset.populate(unicodes=codepoints)
    font_subset.subset(font)
    save_woff2(font, path)
    return ", ".join(unicode_ranges(codepoints))


def subset_rule(font, output, name, text, *, include_ascii=True):
    filename = f"roco-kingdom-sans-{name}.woff2"
    ranges = save_subset(font, output / filename, text, include_ascii=include_ascii)
    return f"""@font-face {{
  font-family: 'Roco Kingdom Sans';
  font-display: swap;
  font-style: normal;
  src: url('./{filename}') format('woff2');
  unicode-range: {ranges};
}}
"""


def prepare_map_fonts(homepage, source_font, output):
    sources = [homepage / "map.html", homepage / "tool-pages.mjs",
               *sorted((homepage / "src/tools").glob("map*.js"))]
    ui_text = "".join(path.read_text(encoding="utf-8") for path in sources)
    root = homepage.parent / "map_data"
    manifest = json.loads((root / "manifest.json").read_bytes())
    content = []
    for entry in manifest["maps"].values():
        text = (root / entry["file"]).read_text(encoding="utf-8")
        scene = json.loads(text)
        ui_text += scene["name"] + scene["season"] + "".join(scene["floors"].values())
        ui_text += "".join(category["className"] + category["genre"] for category in scene["categories"])
        content.append(text)
        content.extend((root / name).read_text(encoding="utf-8") for name in scene["details"])
    ui = subset_rule(TTFont(source_font, recalcTimestamp=False), output, "map", ui_text)
    ui_characters = set(ui_text) | {chr(codepoint) for codepoint in range(0x20, 0x7F)}
    extra = "".join(sorted(set("".join(content)) - ui_characters))
    details = subset_rule(TTFont(source_font, recalcTimestamp=False), output, "map-content", extra,
                          include_ascii=False)
    (output / "roco-fonts-map.css").write_text("/* Generated by prepare-fonts.py map. */\n" + ui + details,
                                             encoding="utf-8")


def main():
    homepage = Path(__file__).resolve().parent
    package = homepage / "node_modules/rocokingdom-ui/dist/fonts"
    output = homepage / "fonts"
    output.mkdir(exist_ok=True)

    sans_file = package / "roco-kingdom-sans.ttf"
    if sys.argv[1:] == ["map"]:
        prepare_map_fonts(homepage, sans_file, output)
        return
    sans = TTFont(sans_file, recalcTimestamp=False)
    if sys.argv[1:] in (["handbook"], ["tools"]):
        page = sys.argv[1]
        if page == "handbook":
            sources = [homepage / "handbook.html", homepage / "src/site.jsx", *sorted((homepage / "src/handbook").glob("*.js*"))]
        else:
            names = ("skill", "eggPred", "pair", "hatch", "home", "adventure", "map")
            sources = [homepage / f"{name}.html" for name in names]
            sources += [homepage / "tool-pages.mjs", homepage.parent / "adventure_rules.txt"]
        text = "".join(path.read_text(encoding="utf-8") for path in sources)
        records = json.loads((homepage.parent / "handbook_data.json").read_text(encoding="utf-8"))["records"]
        for record in records:
            text += record.get("title") or ""
            text += "".join(group for group in record.get("eggGroups") or [] if group)
            text += "".join(attribute for attribute in record.get("attributes") or [] if attribute)
        if page == "tools":
            statements = {(skill.get("name") or "", skill.get("description") or "")
                          for record in records for skill in record.get("skills") or [] if skill}
            text += "".join(name + description for name, description in statements)
        rule = subset_rule(sans, output, page, text)
        (output / f"roco-fonts-{page}.css").write_text(f"/* Generated by prepare-fonts.py {page}. */\n" + rule,
                                                     encoding="utf-8")
        return

    rune = TTFont(package / "roco-kingdom-rune.ttf", recalcTimestamp=False)
    save_woff2(sans, output / "roco-kingdom-sans.woff2")
    save_woff2(rune, output / "roco-kingdom-rune.woff2")

    sources = [homepage / "index.html", *sorted((homepage / "src").glob("*.js*"))]
    text = "".join(path.read_text(encoding="utf-8") for path in sources)
    text += "".join(path.stem for path in (homepage.parent / "web_images/shop").glob("*.png"))
    text += "炼金材料特制咕噜球精灵蛋血脉修改道具限购"
    ranges = save_subset(sans, output / "roco-kingdom-sans-home.woff2", text)

    css = """/* Generated by prepare-fonts.py from the fonts in rocokingdom-ui. */
@font-face {
  font-family: 'Roco Kingdom Sans';
  font-display: swap;
  font-style: normal;
  src: url('./roco-kingdom-sans.woff2') format('woff2');
}

@font-face {
  font-family: 'Roco Kingdom Sans';
  font-display: swap;
  font-style: normal;
  src: url('./roco-kingdom-sans-home.woff2') format('woff2');
  unicode-range: %s;
}

@font-face {
  font-family: 'Roco Kingdom Rune';
  font-display: swap;
  font-style: normal;
  src: url('./roco-kingdom-rune.woff2') format('woff2');
}

:root {
  --rk-font-family-base: 'Roco Kingdom Sans', system-ui, sans-serif;
  --rk-font-family-rune: 'Roco Kingdom Rune', var(--rk-font-family-base);
  --rk-font-family-decorative: var(--rk-font-family-rune);
}
""" % ranges
    (output / "roco-fonts.css").write_text(css, encoding="utf-8")


if __name__ == "__main__":
    main()
